#
# Turn the Armbian image into the artifacts the Xiaomi Redmi K20 Pro (raphael) needs:
#   * <prefix>.system.img   bare ext4 root filesystem, flashed to "userdata"
#   * <prefix>.vendor.img   ext4, mounted at /boot (kernel, initrd, dtb, refind_linux.conf)
#   * <prefix>.cust.img     FAT32, mounted at /boot/efi (rEFInd EFI application)
#   * <prefix>.boot.img     U-Boot packaged as an Android boot image
#   * <prefix>.zip          flashable package for the stock recovery
#
# All of these are generated after the Armbian rootfs image has been built.
#

declare -g RAPHAEL_ROOTFS_UUID="ee8d3593-59b1-480e-a3b6-4fefb17ee7d8"
declare -g -a _RAPHAEL_MOUNTS=()
declare -g -a _RAPHAEL_LOOPS=()
declare -g _RAPHAEL_LAST_LOOP=""

function add_host_dependencies__raphael_host_deps() {
	# dosfstools, e2fsprogs, gdisk, rsync, zip and python3 are already part of
	# the base host dependencies. u-boot 2026.01 uses xxd to generate
	# include/generated/defaultenv_autogenerated.h.
	EXTRA_BUILD_DEPS+=("build-tools::xxd")
}

# Docker only passes the /dev/loopN nodes that existed when the container was
# created, so loops allocated later have no device node and "mount -o loop"
# fails with "failed to setup loop device" (exit 32). Ask losetup which device
# it wants, create the node if needed, then attach the image explicitly.
function raphael_attach_loop() {
	local file="$1" partscan="${2:-no}" loop
	loop="$(losetup -f)"
	if [[ ! -e "${loop}" ]]; then
		mknod -m 0660 "${loop}" b 7 "${loop#/dev/loop}"
	fi
	if [[ "${partscan}" == "yes" ]]; then
		losetup -P "${loop}" "${file}"
		partprobe "${loop}" > /dev/null 2>&1 || true # make sure the partition nodes appear in sysfs
	else
		losetup "${loop}" "${file}"
	fi
	_RAPHAEL_LOOPS+=("${loop}")
	_RAPHAEL_LAST_LOOP="${loop}" # no subshell here, so the cleanup array is kept
}

# Partition device nodes are created by udev, which does not run in the build
# container; build them from sysfs like the Armbian image code does.
function raphael_ensure_loop_part_node() {
	local node="$1" dev
	[[ -e "${node}" ]] && return 0
	dev="$(cat "/sys/class/block/$(basename "${node}")/dev")"
	mknod -m 0660 "${node}" b "${dev%%:*}" "${dev##*:}"
}

function raphael_image_output_cleanup() {
	local mount_point
	for mount_point in "${_RAPHAEL_MOUNTS[@]}"; do
		umount "${mount_point}" 2>/dev/null || true
	done
	_RAPHAEL_MOUNTS=()

	local loop_device
	for loop_device in "${_RAPHAEL_LOOPS[@]}"; do
		losetup -d "${loop_device}" 2>/dev/null || true
	done
	_RAPHAEL_LOOPS=()
}

# xfdesktop keys the backdrop on the XRandR output name. The phone's internal
# panel is "DSI-1", but Armbian's xfce4-desktop.xml only lists monitor0/1 and
# the HDMI/eDP/Virtual outputs, so a fresh home directory comes up with a bare
# grey screen. Add a monitorDSI-1 entry to /etc/skel and to every user home.
function raphael_configure_xfce_backdrop() {
	local root="$1"
	local bg_dir="${root}/usr/share/backgrounds/armbian"
	local bg=""

	for bg in "${bg_dir}/armbian03-Dre0x-Minum-dark-3840x2160.jpg" \
		"${bg_dir}/armbian03-Dre0x-Minum-dark-3840x2160.png"; do
		[[ -f "${bg}" ]] && break || bg=""
	done
	if [[ -z "${bg}" ]]; then
		bg="$(find "${bg_dir}" -maxdepth 1 -type f \( -name '*.jpg' -o -name '*.png' \) 2> /dev/null | sort | head -1)"
	fi
	[[ -n "${bg}" ]] || return 0
	bg="${bg#"${root}"}"

	python3 - "${root}" "${bg}" << 'PY'
import os
import re
import stat
import sys

root, image = sys.argv[1], sys.argv[2]
rel = ".config/xfce4/xfconf/xfce-perchannel-xml/xfce4-desktop.xml"

MINIMAL = """<?xml version="1.0" encoding="UTF-8"?>
<channel name="xfce4-desktop" version="1.0">
  <property name="backdrop" type="empty">
    <property name="screen0" type="empty">
    </property>
  </property>
</channel>
"""


def entries(indent):
    out = []
    for workspace in ("workspace0", "workspace1"):
        out.append(
            f'{indent}<property name="{workspace}" type="empty">\n'
            f'{indent}\t<property name="color-style" type="int" value="0"/>\n'
            f'{indent}\t<property name="image-style" type="int" value="5"/>\n'
            f'{indent}\t<property name="image-path" type="string" value="{image}"/>\n'
            f'{indent}\t<property name="last-image" type="string" value="{image}"/>\n'
            f'{indent}</property>\n'
        )
    return "".join(out)


def patch(text):
    if 'monitorDSI-1' in text:
        return text
    match = re.search(r'^([ \t]*)<property name="screen0" type="empty">[^\n]*\n',
                      text, re.M)
    if match:
        indent = match.group(1) + "\t"
        block = f'{match.group(1)}\t<property name="monitorDSI-1" type="empty">\n' \
                + entries(indent + "\t") \
                + f'{match.group(1)}\t</property>\n'
        return text[:match.end()] + block + text[match.end():]
    match = re.search(r'^([ \t]*)</channel>', text, re.M)
    if match:
        indent = match.group(1) + "\t"
        block = (f'{indent}<property name="backdrop" type="empty">\n'
                 f'{indent}\t<property name="screen0" type="empty">\n'
                 f'{indent}\t\t<property name="monitorDSI-1" type="empty">\n'
                 + entries(indent + "\t\t\t")
                 + f'{indent}\t\t</property>\n'
                 f'{indent}\t</property>\n'
                 f'{indent}</property>\n')
        return text[:match.start()] + block + text[match.start():]
    return text


def configure(path, uid, gid):
    if os.path.exists(path):
        text = open(path, encoding="utf-8").read()
    else:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        text = MINIMAL
    new = patch(text)
    if new == text and os.path.exists(path):
        return False
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(new)
    # Keep the created path components owned by the account that uses them.
    cur = path
    parent = os.path.dirname(os.path.dirname(path))  # .config/xfce4
    while cur.startswith(parent):
        try:
            os.chown(cur, uid, gid)
        except PermissionError:
            break
        cur = os.path.dirname(cur)
    return True


targets = [(os.path.join(root, "etc/skel", rel), 0, 0)]
homes = os.path.join(root, "home")
if os.path.isdir(homes):
    for name in sorted(os.listdir(homes)):
        home = os.path.join(homes, name)
        if name == "lost+found" or not os.path.isdir(home):
            continue
        st = os.stat(home)
        targets.append((os.path.join(home, rel), st.st_uid, st.st_gid))

for path, uid, gid in targets:
    if configure(path, uid, gid):
        print("xfce backdrop: configured", os.path.relpath(path, root))
PY
}

function post_build_image__900_raphael_images() {
	[[ -z "${version}" ]] && exit_with_error "version is not set"

	local bsp_dir="${SRC}/packages/bsp/xiaomi-raphael"
	local work_dir="${DESTIMG}/.raphael-work"
	local prefix="${DESTIMG}/xiaomi-k20pro-${version}"

	local source_image="${DESTIMG}/${version}.img"
	local system_image="${prefix}.system.img"
	local vendor_image="${prefix}.vendor.img"
	local cust_image="${prefix}.cust.img"
	local boot_image="${prefix}.boot.img"

	[[ -f "${source_image}" ]] || exit_with_error "missing source image ${source_image}"

	local old_root="${work_dir}/old-root"
	local new_root="${work_dir}/new-root"
	local vendor_mnt="${work_dir}/vendor"
	local cust_mnt="${work_dir}/cust"

	rm -rf "${work_dir}"
	mkdir -p "${old_root}" "${new_root}" "${vendor_mnt}" "${cust_mnt}"
	add_cleanup_handler raphael_image_output_cleanup

	############################################################ system.img
	local image_loop
	raphael_attach_loop "${source_image}" yes
	image_loop="${_RAPHAEL_LAST_LOOP}"

	local rootfs_part_index
	rootfs_part_index="$(gdisk -l "${source_image}" | awk '$1 ~ /^[0-9]+$/ && $NF == "rootfs" {print $1; exit}')"
	[[ -z "${rootfs_part_index}" ]] && rootfs_part_index=1

	local rootfs_dev="${image_loop}p${rootfs_part_index}"
	raphael_ensure_loop_part_node "${rootfs_dev}"
	mount "${rootfs_dev}" "${old_root}"
	_RAPHAEL_MOUNTS+=("${old_root}")

	############################################################ vendor.img
	# Built first: at runtime /boot is the vendor partition, so the kernel,
	# initrd and DTB stored here are the only copies the phone loads. The same
	# files inside the rootfs (vmlinuz-*, initrd.img-*, uInitrd-* and the 37 MB
	# dtb tree: ~190 MB in total) are deleted before the rootfs is measured.
	display_alert "Creating vendor image" "ext4" "info"
	truncate -s 512M "${vendor_image}"
	mkfs.ext4 -F -L vendor "${vendor_image}"
	local vendor_loop kernel_version dtb_file
	raphael_attach_loop "${vendor_image}"
	vendor_loop="${_RAPHAEL_LAST_LOOP}"
	mount "${vendor_loop}" "${vendor_mnt}"
	_RAPHAEL_MOUNTS+=("${vendor_mnt}")

	kernel_version="$(ls -1 "${old_root}"/boot/vmlinuz-* 2>/dev/null | sed 's|.*/vmlinuz-||' | sort -V | tail -1)"
	[[ -z "${kernel_version}" ]] && exit_with_error "no kernel found in ${old_root}/boot"
	[[ -f "${old_root}/boot/initrd.img-${kernel_version}" ]] || exit_with_error "no initramfs found for ${kernel_version}"

	dtb_file="${old_root}/boot/dtb-${kernel_version}/qcom/sm8150-xiaomi-raphael.dtb"
	[[ -f "${dtb_file}" ]] || dtb_file="$(find "${old_root}/boot" -name 'sm8150-xiaomi-raphael.dtb' | head -1)"
	[[ -n "${dtb_file}" && -f "${dtb_file}" ]] || exit_with_error "sm8150-xiaomi-raphael.dtb not found"

	install -Dm644 "${old_root}/boot/vmlinuz-${kernel_version}" "${vendor_mnt}/vmlinuz-${kernel_version}"
	install -Dm644 "${old_root}/boot/initrd.img-${kernel_version}" "${vendor_mnt}/initrd.img-${kernel_version}"
	install -Dm644 "${dtb_file}" "${vendor_mnt}/dtbs/qcom/sm8150-xiaomi-raphael.dtb"
	install -Dm644 "${bsp_dir}/boot/refind_linux.conf" "${vendor_mnt}/refind_linux.conf"

	umount "${vendor_mnt}"
	_RAPHAEL_MOUNTS=("${old_root}")

	############################################################ rootfs trim
	# Armbian's rootfs->image copy runs rsync with "--exclude=/home/*" because
	# regular images create the user from the first-boot wizard. This image
	# creates the account during provisioning, so the home directory was dropped
	# and login fails with "Could not chdir to home directory". Recreate it from
	# /etc/skel with the ownership recorded in /etc/passwd.
	local p_name p_pass p_uid p_gid p_gecos p_home p_shell
	while IFS=: read -r p_name p_pass p_uid p_gid p_gecos p_home p_shell; do
		[[ ${p_uid} =~ ^[0-9]+$ ]] && ((p_uid >= 1000 && p_uid < 60000)) || continue
		[[ -n ${p_home} && ${p_home} != "/" && ${p_home} != "/nonexistent" ]] || continue
		[[ -d "${old_root}${p_home}" ]] && continue
		install -d -m 0755 -o "${p_uid}" -g "${p_gid}" "${old_root}${p_home}"
		if [[ -d "${old_root}/etc/skel" ]]; then
			cp -a "${old_root}/etc/skel/." "${old_root}${p_home}/"
			chown -R "${p_uid}:${p_gid}" "${old_root}${p_home}"
		fi
		display_alert "Recreated missing home directory" "${p_home} for ${p_name} (uid ${p_uid})" "info"
	done < "${old_root}/etc/passwd"

	raphael_configure_xfce_backdrop "${old_root}"

	# /boot is the vendor partition once fstab is in effect; keep only the mount
	# points so the duplicated kernel/initrd/DTB payload is not shipped twice.
	rm -rf "${old_root}/boot/"*
	mkdir -p "${old_root}/boot/efi"

	# Armbian's prepare_partitions() rewrites /etc/fstab with the UUID of the
	# temporary SD image, which is never the phone's root. system.img below is
	# created with RAPHAEL_ROOTFS_UUID, so write the real table right before it
	# is copied in, and make sure the mount points exist.
	# The persist mount point is /var/lib/rmtfs, not /persist: the sensors package
	# postinst creates /persist -> /mnt/vendor/persist -> /var/lib/rmtfs, and a
	# symlinked mount point confuses systemd's mount unit, so mount the real dir.
	install -d "${old_root}/boot/efi" "${old_root}/var/lib/rmtfs"
	cat > "${old_root}/etc/fstab" <<- FSTAB
	UUID=${RAPHAEL_ROOTFS_UUID} / ext4 errors=remount-ro,x-systemd.growfs 0 1
	PARTLABEL=vendor /boot ext4 errors=remount-ro 0 2
	PARTLABEL=cust /boot/efi vfat umask=0077 0 1
	PARTLABEL=persist /var/lib/rmtfs ext4 nosuid,nodev,noatime 0 1
	FSTAB

	# Armbian runs "apt-get update" (and installs armbian-config) in the image
	# *after* the provisioning cleanup, so /var/lib/apt/lists is recreated
	# (~200 MB) once provisioning has finished. Drop it again here, together
	# with anything the late apt runs restored under /usr/share.
	rm -rf "${old_root}/var/lib/apt/lists/"* "${old_root}/var/cache/apt/archives/"*.deb
	rm -rf "${old_root}/var/cache/apt/archives/partial/"* "${old_root}/tmp/"*
	rm -rf "${old_root}/usr/share/doc/"* "${old_root}/usr/share/man/"* "${old_root}/usr/share/info/"*
	rm -rf "${old_root}/var/lib/systemd/catalog/"*
	rm -rf "${old_root}/var/log/"*

	local used_mb size_mb
	used_mb="$(du -sm "${old_root}" | cut -f1)"

	# system.img is flashed to "userdata" with fastboot, which has no 4 GiB limit.
	# The stock recovery update-binary is an old minzip without ZIP64 support, so
	# the flashable zip can only be built below 4 GiB; when the images outgrow
	# that the zip is skipped (with a warning) instead of failing the build.
	local max_rootfs_mb=6144
	if [[ ${used_mb} -gt ${max_rootfs_mb} ]]; then
		display_alert "Largest directories in rootfs" "$(du -x -m --max-depth=2 "${old_root}" 2> /dev/null | sort -nr | head -12 | awk '{printf "%sM:%s ", $1, $2}')" "wrn"
		display_alert "Largest directories (depth 3)" "$(du -x -m --max-depth=3 "${old_root}/usr" "${old_root}/var" 2> /dev/null | sort -nr | head -12 | awk '{printf "%sM:%s ", $1, $2}')" "wrn"
		exit_with_error "rootfs is ${used_mb}M, above the ${max_rootfs_mb}M rootfs limit" \
			"remove unused packages (e.g. fonts-noto-cjk-extra, libreoffice/thunderbird translations) or lower DESKTOP_TIER"
	fi

	size_mb=$((used_mb + 1024))
	[[ ${size_mb} -lt 4096 ]] && size_mb=4096

	############################################################ system.img
	display_alert "Creating bare rootfs image" "size=${size_mb}M" "info"
	truncate -s "${size_mb}M" "${system_image}"
	mkfs.ext4 -F -L userdata -U "${RAPHAEL_ROOTFS_UUID}" "${system_image}"
	local system_loop
	raphael_attach_loop "${system_image}"
	system_loop="${_RAPHAEL_LAST_LOOP}"
	mount "${system_loop}" "${new_root}"
	_RAPHAEL_MOUNTS+=("${new_root}")

	rsync -aHAX --numeric-ids -x "${old_root}/" "${new_root}/"
	umount "${new_root}"
	umount "${old_root}"
	_RAPHAEL_MOUNTS=()

	e2fsck -pf "${system_image}" || true
	resize2fs -M "${system_image}"
	e2fsck -pf "${system_image}" || true
	e2fsck -pf "${vendor_image}" || true
	resize2fs -M "${vendor_image}"
	e2fsck -pf "${vendor_image}" || true

	############################################################ cust.img
	display_alert "Creating cust (EFI) image" "FAT32" "info"
	truncate -s 128M "${cust_image}"
	mkfs.fat -F 32 -S 4096 -s 1 -v -n "efi" "${cust_image}"
	local cust_loop
	raphael_attach_loop "${cust_image}"
	cust_loop="${_RAPHAEL_LAST_LOOP}"
	mount "${cust_loop}" "${cust_mnt}"
	_RAPHAEL_MOUNTS+=("${cust_mnt}")
	# vfat cannot store ownership, so plain cp (no -a) avoids "Operation not permitted".
	cp -r "${bsp_dir}/boot/efi/." "${cust_mnt}/"
	umount "${cust_mnt}"
	_RAPHAEL_MOUNTS=()

	############################################################ boot.img
	local uboot_deb_name="${image_artifacts_debs_reversioned["uboot"]:-}"
	local uboot_deb="${DEB_STORAGE}/${uboot_deb_name}"
	if [[ -n "${uboot_deb_name}" && -f "${uboot_deb}" ]]; then
		display_alert "Using freshly built U-Boot" "${uboot_deb_name}" "info"
		dpkg -x "${uboot_deb}" "${work_dir}/uboot"
		local built_boot
		built_boot="$(find "${work_dir}/uboot" -name 'boot.img' | head -1)"
		[[ -n "${built_boot}" ]] && cp "${built_boot}" "${boot_image}"
	fi
	if [[ ! -f "${boot_image}" ]]; then
		display_alert "Falling back to packaged U-Boot boot.img" "${bsp_dir}/pack/boot.img" "warn"
		cp "${bsp_dir}/pack/boot.img" "${boot_image}"
	fi

	############################################################ flashable zip
	display_alert "Assembling flashable zip" "${prefix}.zip" "info"

	# Optional custom boot logo: drop 24-bit BMPs (same count/sizes as the stock
	# image) into packages/bsp/xiaomi-raphael/logo/ (or RAPHAEL_LOGO_BMP_DIR) and
	# they replace the stock splash in logo.img, keeping the partition header.
	local logo_image="${bsp_dir}/pack/firmware-update/logo.img"
	local logo_bmp_dir="${RAPHAEL_LOGO_BMP_DIR:-${bsp_dir}/logo}"
	if compgen -G "${logo_bmp_dir}/*.bmp" > /dev/null; then
		display_alert "Building custom logo.img" "${logo_bmp_dir}" "info"
		python3 "${bsp_dir}/tools/create_logo_img_preserve.py" "${logo_bmp_dir}" "${work_dir}/logo.img" "${logo_image}" ||
			exit_with_error "failed to build logo.img from ${logo_bmp_dir}"
		if [[ "$(stat -c %s "${work_dir}/logo.img")" != "$(stat -c %s "${logo_image}")" ]]; then
			exit_with_error "logo.img size changed: BMPs must match the stock dimensions and colour depth"
		fi
		logo_image="${work_dir}/logo.img"
	fi

	local zip_dir="${work_dir}/zip"
	mkdir -p "${zip_dir}/firmware-update"
	cp -a "${bsp_dir}/pack/META-INF" "${zip_dir}/"
	cp "${logo_image}" "${zip_dir}/firmware-update/logo.img"
	cp "${bsp_dir}/pack/firmware-update/vbmeta.img" "${zip_dir}/firmware-update/"
	cp "${bsp_dir}/pack/firmware-update/dtbo.img" "${zip_dir}/firmware-update/"
	cp "${boot_image}" "${zip_dir}/boot.img"
	# Hard-link the multi-GB images instead of copying them (same filesystem).
	ln -f "${system_image}" "${zip_dir}/system.img" 2> /dev/null || cp "${system_image}" "${zip_dir}/system.img"
	ln -f "${vendor_image}" "${zip_dir}/vendor.img" 2> /dev/null || cp "${vendor_image}" "${zip_dir}/vendor.img"
	ln -f "${cust_image}" "${zip_dir}/firmware-update/cust.img" 2> /dev/null || cp "${cust_image}" "${zip_dir}/firmware-update/cust.img"

	# Info-ZIP emits ZIP64 as soon as an entry or the archive reaches 4 GiB.
	# Compression can only shrink the payload, so check the inputs first and
	# avoid spending minutes deflating 3+ GiB for a zip the phone cannot read.
	local zip_input_bytes
	zip_input_bytes="$(du -sb "${zip_dir}" | cut -f1)"
	local zip_skipped=0
	if [[ ${zip_input_bytes} -ge $((4 * 1024 * 1024 * 1024)) ]]; then
		zip_skipped=1
		display_alert "Skipping flashable zip" \
			"inputs are ${zip_input_bytes} bytes; the stock recovery update-binary cannot read ZIP64 (4 GiB). Flash the .img files with fastboot instead." "wrn"
	fi

	if [[ ${zip_skipped} -eq 0 ]]; then
		rm -f "${prefix}.zip"
		(cd "${zip_dir}" && zip -r -q -X "${prefix}.zip" .)

		# Info-ZIP switches to ZIP64 above 4 GiB, which the recovery cannot read.
		local zip_bytes
		zip_bytes="$(stat -c %s "${prefix}.zip")"
		if [[ ${zip_bytes} -ge $((4 * 1024 * 1024 * 1024)) ]]; then
			rm -f "${prefix}.zip"
			zip_skipped=1
			display_alert "Removed flashable zip" \
				"${zip_bytes} bytes needs ZIP64, unsupported by the stock recovery. Flash the .img files with fastboot instead." "wrn"
		fi
	fi

	raphael_image_output_cleanup
	rm -rf "${work_dir}"

	# The GPT image Armbian produced is not flashable to this phone (U-Boot goes
	# to "boot", the rootfs to "userdata"); drop it so the pipeline does not
	# waste minutes compressing 6 GiB into output/images. A note keeps the
	# framework's "<version>.*" move step non-empty.
	rm -f "${source_image}"
	local note="Root filesystem converted to xiaomi-k20pro-${version}.system.img / .vendor.img / .cust.img / .boot.img"
	[[ ${zip_skipped} -eq 0 ]] && note+=" / .zip"
	printf '%s\n' "${note}" > "${DESTIMG}/${version}.img.txt"

	# The build framework only moves "<version>.*" to the final destination.
	mkdir -p "${FINALDEST}"
	mv -v "${prefix}."* "${FINALDEST}/"

	display_alert "Raphael images ready" "$(ls -1sh "${FINALDEST}"/xiaomi-k20pro-"${version}".* | tr '\n' ' ')" "info"
	return 0
}
